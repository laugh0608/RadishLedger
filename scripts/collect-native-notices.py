#!/usr/bin/env python3
"""从锁定的本机包缓存收集移动实验 native 许可；不联网或安装依赖。"""
import argparse
import json
from pathlib import Path
import subprocess
from urllib.parse import unquote, urlparse

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "apps/m0_probe/assets/native-notices.txt"
RUST_LIBRARY = ROOT / "apps/m0_probe/assets/rust-library-notices.html"
TARGETS = ("aarch64-apple-ios", "aarch64-linux-android",
           "aarch64-apple-darwin", "x86_64-unknown-linux-gnu")


def metadata(target):
    return json.loads(subprocess.check_output(
        ["cargo", "metadata", "--offline", "--locked", "--all-features",
         "--format-version", "1", "--filter-platform", target], cwd=ROOT,
    ))


def reachable(document):
    nodes = {node["id"]: node for node in document["resolve"]["nodes"]}
    visited = set()
    pending = list(document["workspace_members"])
    while pending:
        identifier = pending.pop()
        if identifier not in visited:
            visited.add(identifier)
            pending.extend(dep["pkg"] for dep in nodes[identifier]["deps"])
    return visited


def normalize(path):
    # 只统一 UTF-8 / 行尾 / 尾空白，保留原许可正文与归属。
    return "\n".join(line.rstrip() for line in path.read_text().splitlines()).strip() + "\n"


def package_notices(package, frb_root, apache_file):
    base = Path(package["manifest_path"]).parent
    name = package["name"]
    files = [p for p in sorted(base.iterdir()) if p.is_file()
             and p.name.upper().startswith(("LICENSE", "COPYING", "NOTICE"))]
    if name in {"flutter_rust_bridge", "flutter_rust_bridge_macros"}:
        files = [frb_root / "LICENSE"]
    if name == "dart-sys":
        # crate 声明 MIT OR Apache-2.0；选用 Apache-2.0，并保留内含 Dart SDK 的 BSD。
        files = [apache_file, base / "dart-sdk/LICENSE"]
    if name == "sqlcipher-src":
        files = [base / "LICENSE", base / "sqlcipher/LICENSE-sqlcipher",
                 base / "sqlcipher/LICENSE-libtomcrypt"]
    if name == "openssl-src":
        files.append(base / "openssl/LICENSE.txt")
    if not files:
        raise SystemExit(f"缺少 {name} {package['version']} 的许可材料，不能生成空 notice")
    notices = [normalize(path) for path in files]
    if name == "sqlcipher-src":
        # 发布包没有独立 SQLite LICENSE；保留 sqlite3.h 的完整首段版权声明，不另造正文。
        header = normalize(base / "sqlcipher/sqlite3.h")
        comment, separator, _ = header.partition("*/")
        if (not header.startswith("/*") or not separator or len(comment) > 8192
                or "The author disclaims copyright to this source code." not in comment):
            raise SystemExit("sqlcipher-src 的 SQLite 版权声明缺失或格式已变，请复核上游来源")
        notices.append(comment + "*/\n")
    if any(not content.strip() for content in notices):
        raise SystemExit(f"许可文件为空：{name}")
    return notices


def render():
    packages = {}
    for target in TARGETS:
        document = metadata(target)
        used = reachable(document)
        for package in document["packages"]:
            if package["id"] not in used or package["id"] in document["workspace_members"]:
                continue
            if not package["source"]:
                expected = ROOT / "third-party/openssl-sys/Cargo.toml"
                if package["name"] != "openssl-sys" or Path(package["manifest_path"]).resolve() != expected:
                    raise SystemExit("存在未经登记的本地 native 依赖，不能遗漏其许可")
            packages[package["id"]] = package
    config = json.loads((ROOT / "apps/m0_probe/.dart_tool/package_config.json").read_text())
    frb = next(p for p in config["packages"] if p["name"] == "flutter_rust_bridge")
    frb_root = Path(unquote(urlparse(frb["rootUri"]).path))
    if frb_root.name != "flutter_rust_bridge-2.13.0":
        raise SystemExit("FRB 许可来源必须与锁定的 2.13.0 包一致")
    apache = next(p for p in packages.values() if p["name"] == "backtrace")
    apache_file = Path(apache["manifest_path"]).parent / "LICENSE-APACHE"
    groups = {}
    for package in sorted(packages.values(), key=lambda p: (p["name"], p["version"])):
        name = package["name"]
        attribution = f"{name} {package['version']}"
        source = f"https://crates.io/crates/{name}/{package['version']}"
        if not package["source"]:
            attribution += " (RadishLedger local source-dependency patch)"
        for content in package_notices(package, frb_root, apache_file):
            groups.setdefault(content, set()).add(f"{attribution} — {source}")
    result = [
        "RadishLedger M0 native dependency notices",
        "Generated by scripts/collect-native-notices.py from Cargo.lock and local package licenses.",
        "Targets: Android / iOS arm64, macOS arm64 and Linux x64 validation hosts.",
        "Includes build dependencies; this is a conservative superset, not a binary license scan.",
        "Identical license texts are grouped. Third-party rights are independent of the project LICENSE.",
        "allo-isolate uses its packaged Apache-2.0 LICENSE (Cargo license metadata is absent).",
        "dart-sys uses its declared Apache-2.0 alternative; its embedded Dart SDK BSD notice is retained.",
        "FRB Rust crates use the same upstream 2.13.0 MIT notice supplied in the Dart package.",
        "SQLCipher and OpenSSL notices include their bundled upstream licenses.",
        "sqlcipher-src includes SQLCipher, SQLite's header notice and libtomcrypt's dual license; libtomcrypt is not selected by our native builds.",
        "",
    ]
    for content, owners in groups.items():
        result.extend(["=" * 72, *sorted(owners), "", content.rstrip(), ""])
    return "\n".join(result).rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    sysroot = Path(subprocess.check_output(["rustc", "--print", "sysroot"], cwd=ROOT, text=True).strip())
    rust_library = normalize(sysroot / "share/doc/rust/COPYRIGHT-library.html").encode()
    if args.check:
        if (not OUTPUT.is_file() or OUTPUT.read_text() != expected
                or not RUST_LIBRARY.is_file() or RUST_LIBRARY.read_bytes() != rust_library):
            raise SystemExit("Native notices 已漂移，请在依赖缓存齐备后重新生成")
        print("Native notices 与锁定依赖许可一致")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected)
        RUST_LIBRARY.write_bytes(rust_library)
        print(f"Native notices 已生成：{len(expected.encode())} bytes")


if __name__ == "__main__":
    main()
